import { chromium } from 'playwright';
import { createServer } from 'node:http';
import { readFile } from 'node:fs/promises';
const srv = createServer(async (req,res)=>{ try{ res.writeHead(200,{'content-type':'text/html'}); res.end(await readFile('dist/index.html')); }catch(e){res.writeHead(404).end('x');} });
await new Promise(r=>srv.listen(0,'127.0.0.1',r));
const URL=`http://127.0.0.1:${srv.address().port}/`;
const b = await chromium.launch({ args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader'] });
const errs=[];
const p = await b.newPage({viewport:{width:1280,height:720}});
p.on('pageerror',e=>errs.push(String(e))); p.on('console',m=>{if(m.type()==='error')errs.push(m.text());});
await p.goto(URL,{waitUntil:'load'}); await p.waitForTimeout(2000);
await p.screenshot({path:'artifacts/x-menu.png'});
await p.click('#start'); await p.waitForTimeout(700);
await p.click('#arm-grid .arm-card >> nth=0'); await p.waitForTimeout(4200);
await p.screenshot({path:'artifacts/x-play.png'});
await p.keyboard.down('Space'); await p.waitForTimeout(3000); await p.keyboard.up('Space');
await p.screenshot({path:'artifacts/x-press.png'});
const stats = await p.evaluate(async () => {
  const s = window.__tentaclash;
  let frames=0, t0=performance.now();
  await new Promise(r=>{ const tick=()=>{frames++; if(performance.now()-t0<1000) requestAnimationFrame(tick); else r();}; requestAnimationFrame(tick); });
  return { fps: frames, calls: s.stats(), size: s.canvas() };
});
console.log('fps(swiftshader):', stats.fps, 'drawCalls:', stats.calls, 'canvas:', stats.size.join('x'));
console.log('errors:', errs.length ? errs.slice(0,4) : 'none');
const m = await b.newPage({viewport:{width:390,height:844}, isMobile:true, hasTouch:true});
await m.goto(URL,{waitUntil:'load'}); await m.waitForTimeout(1500);
await m.screenshot({path:'artifacts/x-mobile-menu.png'});
await b.close(); srv.close();
